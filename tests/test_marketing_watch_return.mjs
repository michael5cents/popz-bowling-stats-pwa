import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import vm from 'node:vm';
const root=resolve(import.meta.dirname,'..');
const read=name=>readFileSync(resolve(root,'marketing/professional-site',name),'utf8');
const html=read('watch.html'),script=read('watch.js'),site=read('index.html');
assert.match(html,/id="commercial" controls preload="metadata"/);
assert.match(html,/width="1280" height="720"/);
assert.match(html,/href="\/features\/#demo"/);
assert.match(html,/src="assets\/Popz-Bowling-League-Night-Safari-Compatible.mp4"/);
assert.match(html,/If your older iPad won't show the picture/);
assert.doesNotMatch(html,/<dialog|backdrop-filter|filter:blur/);
assert.equal((site.match(/href="watch" data-video-open/g)||[]).length,4);
assert.doesNotMatch(site,/<button[^>]*data-video-open/);
const playEvents={},playClicks={},returns=[],status={textContent:''},button={addEventListener(type,fn){playClicks[type]=fn}};
const video={ended:false,duration:52.875,currentTime:0,addEventListener(type,fn){playEvents[type]=fn},play(){return Promise.resolve()}};
const document={getElementById(id){return {'commercial':video,'play-commercial':button,'watch-status':status}[id]}};
vm.runInNewContext(script,{document,window:{location:{replace(href){returns.push(href)}}},Number,console});
assert.equal(typeof playClicks.click,'function');
assert.equal(typeof playEvents.ended,'function');
assert.equal(typeof playEvents.webkitendfullscreen,'function');
playClicks.click();
video.currentTime=22;
playEvents.webkitendfullscreen();
assert.equal(returns.length,0,'early exit from fullscreen must not prematurely return');
video.currentTime=52.7;
playEvents.webkitendfullscreen();
assert.deepEqual(returns,['/features/#demo'],'completion in iOS native fullscreen returns to website');
playEvents.ended();
assert.equal(returns.length,1,'two completion signals must only redirect once');
const returns2=[],video2={...video,currentTime:0,ended:false,addEventListener(type,fn){playEvents[type]=fn}};
vm.runInNewContext(script,{document:{getElementById(id){return id==='commercial'?video2:id==='play-commercial'?button:status}},window:{location:{replace(href){returns2.push(href)}}},Number,console});
playEvents.ended();
assert.deepEqual(returns2,['/features/#demo'],'regular video completion returns to the website');
console.log('Marketing commercial return-to-site events, iOS fullscreen exit, full-HD fallback and navigation links verified');
